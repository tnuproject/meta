#!/usr/bin/env python3
"""Generates registries from a FreeBSD source tree.

usage: generate.py FREEBSD_SOURCE RELEASE linuxulator|linuxkpi > FILE

The registries state what the source says, not what was tested:

linuxulator  every Linux system call on amd64: implemented, or a placeholder
linuxkpi     every function LinuxKPI declares, marking the ones its own source
             calls unfinished
"""

import pathlib
import re
import sys

COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.DOTALL)
STUB = re.compile(r"\b(TODO|UNIMPLEMENTED|IMPROVE_TODO)\b")
WORDS = re.compile(r"\b[a-z_][a-z0-9_]{2,}\b")

# Where each area of LinuxKPI lives, by header. First match wins.
AREAS = [
    ("pci", r"linux/pci|linux/msi|linux/aer"),
    ("usb", r"linux/usb"),
    ("dma", r"linux/dma|linux/scatterlist|linux/iommu"),
    ("memory", r"linux/(mm|slab|gfp|vmalloc|page|highmem|shrinker|kmemleak|mempool|io\b|io-)"),
    ("synchronization", r"linux/(mutex|spinlock|rw|seq|completion|wait|atomic|rcu|srcu|ww_|llist|lock|sem|refcount|kref|xarray|idr)|asm/atomic"),
    ("workqueues", r"linux/(workqueue|kthread|irq_work|tasklet|timer|hrtimer|delay)"),
    ("interrupts", r"linux/(interrupt|irq)"),
    ("wireless", r"net/(mac80211|cfg80211|ieee80211|regulatory|netmem|page_pool)|linux/ieee80211|linux/(mhi|qrtr|soc/qcom|soc/mediatek)"),
    ("networking", r"linux/(netdevice|skbuff|etherdevice|if_|net|ip|tcp|udp|in\d?|socket)|net/"),
    ("graphics", r"linux/(fb|backlight|console|vga|hdmi|i2c|dmi|agp)|video/|drm/"),
    ("firmware", r"linux/firmware"),
    ("power", r"linux/(pm|suspend|acpi|power|thermal|hwmon)|acpi/"),
    ("crypto", r"crypto/|linux/crypto"),
    ("debug", r"linux/(debugfs|seq_file|sysfs|kobject|device|ktime|tracepoint|relay)"),
]


def read(path):
    return path.read_text(encoding="utf-8", errors="replace")


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def linuxulator(source, release):
    calls = {}
    kinds = set("STD NOPROTO UNIMPL OBSOL".split())
    for line in read(source / "sys/amd64/linux/syscalls.master").splitlines():
        fields = line.split()
        if len(fields) < 3 or not re.fullmatch(r"\d+", fields[0]) or fields[2] not in kinds:
            continue
        number, kind = int(fields[0]), fields[2]
        rest = " ".join(fields[3:])
        name = re.search(r"linux_(\w+)\(", rest) or re.match(r"(\w+)", rest)
        if name:
            calls[number] = [name[1], "placeholder" if kind == "UNIMPL" else "implemented"]
        else:
            calls[number] = [None, "implemented" if kind != "UNIMPL" else "placeholder"]
    # Definitions continue on following lines when they are long.
    text = read(source / "sys/amd64/linux/syscalls.master")
    for match in re.finditer(r"^(\d+)\s+\S+\s+(STD|NOPROTO)\s*\{\s*(.*?)\}", text,
                             re.MULTILINE | re.DOTALL):
        name = re.search(r"\b(\w+)\s*\(", match[3])
        if name:
            calls[int(match[1])][0] = re.sub(r"^linux_", "", name[1]).removeprefix("sys_")
    dummies = set()
    for path in ("sys/compat/linux/linux_dummy.c", "sys/amd64/linux/linux_dummy_machdep.c"):
        file = source / path
        if file.exists():
            dummies.update(re.findall(r"^(?:DUMMY|UNIMPLEMENTED)\((\w+)\)", read(file), re.MULTILINE))
    print(f"# Linux system calls in FreeBSD {release}, amd64. Generated by generate.py from")
    print("# sys/amd64/linux/syscalls.master and the placeholder definitions. Do not edit.")
    print(f"schema = 1\nrelease = {quote(release)}\narchitecture = \"amd64\"\n")
    implemented, placeholder = [], []
    for number in sorted(calls):
        name, state = calls[number]
        if not name or name == "nosys":
            continue
        name = re.sub(r"^linux_", "", name)
        (placeholder if state == "placeholder" or name in dummies else implemented).append((number, name))
    for title, items in (("implemented", implemented), ("placeholder", placeholder)):
        print(f"[{title}]")
        for number, name in items:
            print(f"{name} = {number}")
        print()


def linuxkpi(source, release):
    kpi = source / "sys/compat/linuxkpi"
    include = kpi / "common/include"
    dummy = kpi / "dummy/include"
    stub_names = set()
    everything = list(include.rglob("*.h")) + list((kpi / "common/src").glob("*"))
    defined = set()
    for path in everything:
        if not path.is_file():
            continue
        text = read(path)
        # A definition: name, parameters, and a brace at the start of a line.
        for match in re.finditer(r"^(?:static\s+)?(?:__?\w+\s+)*[\w\s*]*?\b(\w+)\s*\([^;{}]*\)\s*\n?\{(.*?)^\}",
                                 text, re.MULTILINE | re.DOTALL):
            defined.add(match[1])
            if STUB.search(match[2]):
                stub_names.add(match[1])
        for match in re.finditer(r"^[ \t]*#[ \t]*define[ \t]+(\w+)\(((?:[^\n\\]|\\\n)*)", text, re.MULTILINE):
            defined.add(match[1])
            if STUB.search(match[2]):
                stub_names.add(match[1])
    print(f"# LinuxKPI in FreeBSD {release}. Generated by generate.py. Do not edit.")
    print("# 'functions' are declared by the header; 'unfinished' ones say so in their source.")
    print(f"schema = 1\nrelease = {quote(release)}\n")
    for path in sorted(include.rglob("*.h")):
        header = path.relative_to(include).as_posix()
        text = COMMENT.sub("", read(path))
        names = set(re.findall(r"^[ \t]*#[ \t]*define[ \t]+([a-z_]\w{2,})\(", text, re.MULTILINE))
        for match in re.finditer(r"^[A-Za-z_][\w \t*]*?[ \t*\n](\w{3,})[ \t]*\([^;{}#]*\)[^;{}#]*[;{]", text, re.MULTILINE):
            names.add(match[1])
        names = sorted(n for n in names if n != "if" and n.islower() or n in stub_names)
        if not names:
            continue
        area = next((a for a, p in AREAS if re.match(p, header)), "other")
        print(f"[header.{quote(header)}]\narea = {quote(area)}")
        functions = [n for n in names if n not in stub_names]
        unfinished = [n for n in names if n in stub_names]
        print("functions = [" + ", ".join(quote(n) for n in functions) + "]")
        if unfinished:
            print("unfinished = [" + ", ".join(quote(n) for n in unfinished) + "]")
        print()
    empty = sorted(p.relative_to(dummy).as_posix() for p in dummy.rglob("*.h"))
    real = {p.relative_to(include).as_posix() for p in include.rglob("*.h")}
    print("# Headers that exist only so that drivers compile; they declare nothing useful.")
    print("[placeholder_headers]\nnames = [" + ", ".join(quote(h) for h in empty if h not in real) + "]")


def main():
    if len(sys.argv) != 4 or sys.argv[3] not in ("linuxulator", "linuxkpi"):
        sys.exit(__doc__)
    source = pathlib.Path(sys.argv[1])
    if not (source / "sys/compat/linuxkpi").is_dir():
        sys.exit("generate.py: not a FreeBSD source tree")
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    {"linuxulator": linuxulator, "linuxkpi": linuxkpi}[sys.argv[3]](source, sys.argv[2])


if __name__ == "__main__":
    main()
